/* eslint-disable @typescript-eslint/no-unused-expressions -- Playwright CLI evaluates this function expression in an isolated QA browser. */
async (page) => {
  const base = "http://localhost:3038";
  const errors = [];
  page.on("pageerror", (e) => errors.push(e.message));
  const check = (v, message) => { if (!v) throw Error(message); };
  const button = (name) => page.getByRole("button", { name, exact: true });
  const coach = () => page.evaluate(() => JSON.parse(localStorage.getItem("buddymine_game_coach_v1")));
  await page.goto(base + "/games");
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await page.getByText("Bring a game from PGN", { exact: true }).click();
  await page.getByLabel("PGN to import").fill('[Event "Retry integration fixture"]\n[White "QA White"]\n[Black "QA Black"]\n\n1. e4 e5 2. Bc4 Nc6 3. Qh5 Nf6 4. Qxe5+ Nxe5 *');
  await page.getByLabel("Your side in imported game").selectOption("white");
  await button("Import PGN").click();
  await page.getByText(/PGN imported/).waitFor();
  const original = await page.evaluate(() => localStorage.getItem("buddymine_games_v1"));
  const game = JSON.parse(original)[0];
  check(game.moves.every((m) => m.cpLoss === undefined), "Imported fixture unexpectedly annotated");
  await page.getByRole("link", { name: "Learn", exact: true }).click();
  await button("Scan 4 decisions").waitFor({ state: "visible" });
  await page.waitForFunction(() => Array.from(document.querySelectorAll("button")).some((b) => b.textContent === "Scan 4 decisions" && !b.disabled));
  await button("Scan 4 decisions").click();
  await button("Stop scan").waitFor();
  await button("Stop scan").click();
  await page.getByText(/Scan stopped/).waitFor();
  const afterCancel = (await coach())?.analyses.length ?? 0;
  await page.waitForTimeout(1200);
  check(((await coach())?.analyses.length ?? 0) === afterCancel, "Stale scan wrote after cancellation");
  const scanAgain = page.getByRole("button", { name: /^Scan \d+ decisions$/ });
  await scanAgain.click();
  await page.getByText("4 of 4 decisions checked · 0 still available").waitFor({ timeout: 30000 });
  const analyses = (await coach()).analyses;
  const mistake = analyses.find((a) => a.source.ply === 7);
  check(mistake && mistake.teachable, "Real Stockfish did not detect the missed mate");
  check(mistake.before.kind === "mate" && mistake.before.winner === "white", "Wrong mate perspective");
  await page.getByRole("button", { name: /Move 4\. · White · Qxe5/ }).click();
  await page.getByLabel("Your retry move").waitFor({ timeout: 30000 });
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.waitForTimeout(300);
  await page.screenshot({ path: "output/portfolio-upgrade-oct23-round3/white-retry-desktop.png", fullPage: true });
  await page.getByLabel("Your retry move").fill("Qxe5+");
  await button("Check move").click();
  await page.getByText(/The board is reset so you can try another move/).waitFor({ timeout: 30000 });
  check((await coach()).attempts.at(-1).outcome === "not-yet", "Failed retry not recorded");
  await button("A small hint").click();
  await page.getByText("Help step 1 of 2").waitFor();
  await page.getByLabel("Your retry move").fill("Qxf7#");
  await button("Check move").click();
  await page.getByRole("heading", { name: "What changes on the board?" }).waitFor();
  const attempt = (await coach()).attempts.at(-1);
  check(attempt.outcome === "supported", "Assistance ignored");
  check(attempt.gameId === game.id && attempt.ply === 7 && attempt.fenBefore === mistake.source.fenBefore, "Retry source not preserved");
  check(attempt.evaluation.kind === "mate" && attempt.evaluation.winner === "white" && attempt.evaluation.moves === 0, "Terminal mate not recognized");
  await button("Show original move").click();
  await button("Next in line").click();
  await button("Show engine line").click();
  await page.screenshot({ path: "output/portfolio-upgrade-oct23-round3/white-feedback-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 375, height: 812 });
  await page.waitForTimeout(400);
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "Mobile overflow");
  await page.screenshot({ path: "output/portfolio-upgrade-oct23-round3/white-feedback-mobile.png", fullPage: true });
  await button("Next decision").click();
  await page.reload();
  await page.getByRole("heading", { name: "What happened when you tried?" }).waitFor();
  check((await coach()).attempts.length === 2, "Attempt persistence failed");
  check(await page.evaluate(() => localStorage.getItem("buddymine_games_v1")) === original, "Game modified by coaching");
  await page.goto(base + `/learn?game=${game.id}&ply=7`);
  await page.getByLabel("Your retry move").waitFor({ timeout: 30000 });
  await page.screenshot({ path: "output/portfolio-upgrade-oct23-round3/white-retry-mobile.png", fullPage: true });
  const boardTop = await page.locator('[data-square="a8"]').evaluate((el) => el.getBoundingClientRect().top);
  const savedCoach = await page.evaluate(() => localStorage.getItem("buddymine_game_coach_v1"));
  await page.evaluate(() => localStorage.setItem("buddymine_game_coach_v1", "unreadable"));
  await page.reload();
  await page.getByText(/Your game-coach history could not be read/).waitFor();
  await page.getByLabel("Your retry move").waitFor({ timeout: 30000 });
  await button("Walk me through it").click();
  check(await page.evaluate(() => localStorage.getItem("buddymine_game_coach_v1")) === "unreadable", "Corrupt coach data overwritten");
  await page.evaluate((raw) => localStorage.setItem("buddymine_game_coach_v1", raw), savedCoach);
  await page.reload();
  await page.getByLabel("Your retry move").waitFor({ timeout: 30000 });
  check(errors.length === 0, errors.join("\n"));
  const result = { checks: "Imported unannotated PGN; real Stockfish scan; stop/restart with no stale write; exact missed-mate position; original move rejected; hint-aware supported mate; source-linked evidence; line replay; unchanged game; reload; mobile no overflow; corrupt data preserved", gameId: game.id, analyzed: analyses.length, attempts: 2, boardTop, errors };
  await page.evaluate((result) => { window.__gameCoachQA = result; }, result);
  return result;
}
