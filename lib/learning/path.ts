export const COURSE_ORDER = COURSE_STAGES.flatMap((stage) => [
  ...stage.lessons,
]);
export function courseProgress(attempts: Attempt[], now = Date.now()) {
  const valid = attempts
    .filter((a) => Date.parse(a.at) <= now)
    .sort((a, b) => Date.parse(a.at) - Date.parse(b.at));
  const latest = new Map(valid.map((a) => [a.lessonId, a]));
  const transfer = new Map(
    valid.filter((a) => a.stage === "transfer").map((a) => [a.lessonId, a]),
  );
  // A harder new board does not erase an independent result on another board.
  // Retrying the same position and reply line replaces that line’s latest evidence.
  const positionResults = new Map(valid.filter(a => a.stage === "transfer")
    .map(a => [`${a.lessonId}:${a.positionId ?? "transfer-1"}:${a.lineId ?? "line-1"}`, a]));
  const independent = new Set([...positionResults.values()]
    .filter(a => a.outcome === "independent").map(a => a.lessonId));
  const stages = COURSE_STAGES.map((stage) => ({
    ...stage,
    independent: stage.lessons.filter((id) => independent.has(id)).length,
    tried: stage.lessons.filter((id) => latest.has(id)).length,
  }));
  const nextId =
    COURSE_ORDER.find((id) => !independent.has(id)) ?? COURSE_ORDER[0];
  return {
    latest,
    transfer,
    independent,
    stages,
    next: LESSONS.find((l) => l.id === nextId)!,
  };
}
export function firstPrerequisite(
  id: string,
  independent: Set<string>,
  seen = new Set<string>(),
): string | null {
  if (seen.has(id)) return null;
  seen.add(id);
  for (const prerequisite of PREREQUISITES[id] ?? []) {
    if (!independent.has(prerequisite))
      return firstPrerequisite(prerequisite, independent, seen) ?? prerequisite;
  }
  return null;
}
